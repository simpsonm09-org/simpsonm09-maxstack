# Writes, keeps, or removes one gate hook file from its plan. A changed file or one maxstack did not write is kept.
function Write-GateHookConfig {
    param($Plan)

    if ($null -eq $Plan) { return }
    $relative = [string] (Get-Field $Plan 'path')
    $label = [string] (Get-Field $Plan 'label')
    $full = Join-Path $Workspace ($relative -replace '/', '\')
    $prior = Get-PriorOwnedFileRecord $relative
    if (Test-IsTrue (Get-Field $Plan 'preserve')) { return }
    if (Test-IsTrue (Get-Field $Plan 'remove')) {
        if ($null -eq $prior -or -not (Test-Path -LiteralPath $full -PathType Leaf)) { return }
        Remove-Item -LiteralPath $full -Force
        Write-Host "Removed ${relative}: no selected layer ships a $label gate hook."
        return
    }
    if ((Test-Path -LiteralPath $full -PathType Leaf) -and (Test-OrdinalEqual (Get-FileHash -LiteralPath $full -Algorithm SHA256).Hash $Plan.sha256) -and (Test-OrdinalEqual ([IO.File]::ReadAllText($full)) $Plan.text)) {
        Write-Host "$label hook config already matches: $relative"
        return
    }
    New-Item -ItemType Directory -Path (Split-Path -Parent $full) -Force | Out-Null
    Write-FileAtomically $full $Plan.text
    Write-Host "Wrote $relative"
}

# Codex output uses one fixed Launch argument. A selected gate hook adds a one-time approval step and a hash-change note.
function Write-CodexNotes {
    param([object[]] $Layers, [bool] $Applying, [bool] $OpenCodeSelected, $WorkspaceInstructionPlan, $HookConfigPlan)

    if ($null -ne $WorkspaceInstructionPlan -and $WorkspaceInstructionPlan.text) {
        $agentsFile = @($WorkspaceInstructionPlan.files | Where-Object { Test-OrdinalEqual $_.path 'AGENTS.md' }) | Select-Object -First 1
        if ($null -ne $agentsFile) {
            if (Test-IsTrue (Get-Field $agentsFile 'preserve')) { $agentsNote = 'Codex: workspace AGENTS.md was kept because it changed by hand.' }
            else { $agentsNote = 'Codex: workspace AGENTS.md was generated from the selected layers.' }
        } elseif (Test-OrdinalIn 'AGENTS.md' $WorkspaceInstructionPlan.collisionNames) {
            $agentsNote = 'Codex: workspace AGENTS.md was kept because it was not written by maxstack.'
        } else {
            $agentsNote = 'Codex: no workspace AGENTS.md was generated; shared instructions were written to .maxstack/workspace-instructions.md.'
        }
    } else {
        $agentsNote = 'Codex: no workspace AGENTS.md was generated. Any existing one is read only when the launch arguments name stack.lock.json.'
    }
    $agentsNote += ' Codex reads it only with the marker launch argument.'

    $gateLayers = @(Get-CodexGateLayers -Layers $Layers)
    if ($gateLayers.Count -gt 1) { Write-Host $script:CodexGateOneNote }
    if (-not $Applying) {
        Write-Host $script:CodexLaunchLine
        if ($gateLayers.Count -gt 0) {
            $note = if ($null -ne (Get-PriorOwnedFileRecord $script:CodexConfigPath)) { $script:CodexGateRecordedNote } else { $script:CodexGateAuditNote }
            Write-Host $note
        }
        if ($null -ne $HookConfigPlan -and $null -ne (Get-Field $HookConfigPlan 'hookHash')) { Write-Host "Codex: current hook hash: $(Get-Field $HookConfigPlan 'hookHash')" }
        if ($null -ne $HookConfigPlan -and $null -ne (Get-Field $HookConfigPlan 'hookHash') -and $null -ne (Get-PriorOwnedFileRecord $script:CodexConfigPath) -and -not (Test-OrdinalEqual (Get-Field $HookConfigPlan 'hookHash') (Get-Field (Get-PriorOwnedFileRecord $script:CodexConfigPath) 'hookHash'))) { Write-Host 'the Codex hook changed since the last apply: approve it again in Codex' }
        Write-Host $agentsNote
        return
    }
    Write-Host $script:CodexLaunchLine
    if ($null -ne $HookConfigPlan -and $null -ne (Get-Field $HookConfigPlan 'hookHash')) { Write-Host "Codex: current hook hash: $(Get-Field $HookConfigPlan 'hookHash')" }
    if ($null -ne $HookConfigPlan -and $null -ne (Get-Field $HookConfigPlan 'hookHash') -and $null -ne (Get-PriorOwnedFileRecord $script:CodexConfigPath) -and -not (Test-OrdinalEqual (Get-Field $HookConfigPlan 'hookHash') (Get-Field (Get-PriorOwnedFileRecord $script:CodexConfigPath) 'hookHash'))) { Write-Host 'the Codex hook changed since the last apply: approve it again in Codex' }
    if ($gateLayers.Count -gt 0) { Write-Host $script:CodexOneTimeNote }
    Write-Host $agentsNote
}
