# Reads a SKILL.md frontmatter the way the generator does: the block between the first two --- lines, one key per line.
# A key that is not name or description is read and kept, so a model key is found and refused by the caller.
function Read-SkillFields {
    param([string] $Path, [string] $Label)

    $text = [IO.File]::ReadAllText($Path)
    $lines = @($text.TrimStart([char] 0xFEFF) -split '\r?\n')
    $end = [Array]::IndexOf($lines, '---', 1)
    if ($lines.Count -eq 0 -or -not (Test-OrdinalEqual $lines[0] '---') -or $end -lt 1) { throw "$Label needs a --- frontmatter block." }
    $fields = [hashtable]::new([StringComparer]::Ordinal)
    for ($index = 1; $index -lt $end; $index++) {
        $match = [regex]::Match($lines[$index], '^([A-Za-z][\w-]*):\s*(.*)$')
        if (-not $match.Success) { continue }
        $value = $match.Groups[2].Value.Trim()
        $quoted = [regex]::Match($value, '^(["''])(.*)\1$')
        if ($quoted.Success) { $value = $quoted.Groups[2].Value }
        $fields[$match.Groups[1].Value] = $value
    }
    return $fields
}

# Every entry of a skill folder, with links listed and never followed. A link anywhere in the skill is refused.
function Assert-SkillFolder {
    param([string] $Folder, [string] $Label, [string] $Runtime = 'codex')

    if (Test-ReparsePoint $Folder) { throw "$Label is a symbolic link or junction, so $Runtime cannot take it. Replace it with a folder." }
    foreach ($entry in @(Get-TreeEntries -Root $Folder -Rule 'owned')) {
        if ($null -ne $entry.link) { throw "$Label holds a symbolic link or junction at $($entry.relative), which a skill may not hold." }
    }
}

# The frontmatter a skill must carry. A model key is refused, since maxstack sets no model. A missing name or description is refused.
function Assert-SkillFields {
    param([string] $Path, [string] $Name, [string] $Label)

    $fields = Read-SkillFields -Path $Path -Label $Label
    if ($fields.ContainsKey('model')) { throw "$Label`: frontmatter model is not allowed; maxstack sets no model." }
    if (-not (Test-NonEmptyString $fields['name'])) { throw "$Label`: frontmatter name is missing or empty." }
    if (-not (Test-OrdinalEqual $fields['name'] $Name)) { throw "$Label`: frontmatter name '$($fields['name'])' must equal the folder name '$Name'." }
    if (-not (Test-NonEmptyString $fields['description'])) { throw "$Label`: frontmatter description is missing or empty." }
}

# Copies a skill folder, leaving out node_modules at any depth, as the generator does. The copy hashes like its source.
function Copy-SkillTree {
    param([string] $Source, [string] $Destination)

    New-Item -ItemType Directory -Path $Destination -Force | Out-Null
    foreach ($child in @(Get-ChildItem -LiteralPath $Source -Force)) {
        if (Test-OrdinalEqual $child.Name 'node_modules') { continue }
        $target = Join-MaxstackPath $Destination $child.Name
        if ($child.PSIsContainer) { Copy-SkillTree -Source $child.FullName -Destination $target }
        else { Copy-Item -LiteralPath $child.FullName -Destination $target -Force }
    }
}

# The skills the selected runtime's layers contribute, in layer order. Each entry names the skill, its layer, its source folder,
# and the owned hash its installed copy will hold. A layer whose root is not known yet (a pinned cache not at its pin) adds
# nothing, so only audit sees it, and its records read as drifted until an apply syncs it.
function Get-LayerSkills {
    param([object[]] $Layers, [string] $Runtime = 'codex')

    $skills = [System.Collections.Generic.List[object]]::new()
    $claimed = [hashtable]::new([StringComparer]::OrdinalIgnoreCase)
    foreach ($layer in @($Layers | Where-Object { $_.runtimes.ContainsKey($Runtime) })) {
        if ($null -eq $layer.root) { continue }
        $skillsRoot = Join-MaxstackPath $layer.root 'skills'
        if (-not (Test-Path -LiteralPath $skillsRoot -PathType Container)) { continue }
        if (Test-ReparsePoint $skillsRoot) { throw "Layer '$($layer.name)' has a symbolic link or junction at skills, which $Runtime cannot read." }
        $names = [System.Collections.Generic.List[string]]::new()
        foreach ($child in @(Get-ChildItem -LiteralPath $skillsRoot -Force)) {
            if ($child.Name.StartsWith('.', [StringComparison]::Ordinal)) { continue }
            if (-not $child.PSIsContainer) { Write-Warning "ignored skills/$($child.Name) in layer '$($layer.name)': not a skill folder"; continue }
            $names.Add($child.Name)
        }
        $seen = [hashtable]::new([StringComparer]::OrdinalIgnoreCase)
        foreach ($name in $names) {
            if ($seen.ContainsKey($name)) { throw "Layer '$($layer.name)' has skill folders whose names differ only by case, which $Runtime cannot tell apart: $($seen[$name]) and $name." }
            $seen[$name] = $name
        }
        foreach ($name in (Sort-Utf8 $names.ToArray())) {
            $label = "Layer '$($layer.name)' skill '$name'"
            if (-not [regex]::IsMatch($name, '^[A-Za-z0-9][A-Za-z0-9-]*\z')) { throw "$label`: skill folder names must be letters, digits, and hyphens." }
            $folder = Join-MaxstackPath $skillsRoot $name
            Assert-SkillFolder -Folder $folder -Label $label -Runtime $Runtime
            $skillFile = @(Get-ChildItem -LiteralPath $folder -File -Force | Where-Object { Test-OrdinalEqual $_.Name 'SKILL.md' })
            if ($skillFile.Count -eq 0) { throw "$label`: a file named exactly SKILL.md is required." }
            Assert-SkillFields -Path $skillFile[0].FullName -Name $name -Label $label
            if ($claimed.ContainsKey($name)) {
                throw "duplicate skill $name across layers: $($claimed[$name]) and $($layer.name) both name it, and $Runtime finds a skill by its folder name. Rename one of them."
            }
            $claimed[$name] = $layer.name
            $skills.Add([pscustomobject]@{ name = $name; layer = $layer.name; source = $folder; sha256 = (Get-TreeSha256 $folder) })
        }
    }
    return $skills.ToArray()
}

# Whether a path under .agents\skills is one the lock records as codex's own folder, with the record.
function Get-CodexRecord {
    param([object[]] $Owned, [string] $Relative)

    return @($Owned | Where-Object { $null -ne $_ -and (Test-OrdinalEqual $_.path $Relative) -and (Test-OrdinalEqual $_.kind 'dir') -and (@(Get-OwnedRuntimeClaims $_ | Where-Object { Test-OrdinalIn $_ @('codex', 'antigravity') }).Count -gt 0) }) | Select-Object -First 1
}

function Assert-CodexSkillsPath {
    # Folders above the workspace are the user's choice and may be system links (macOS /var is a
    # link to /private/var), so only the folders below it are checked, as the Cursor installer does.
    $workspace = [IO.Path]::GetFullPath($Workspace)
    $current = $workspace
    foreach ($segment in @('.agents', 'skills')) {
        $current = Join-Path $current $segment
        if (-not (Test-Path -LiteralPath $current)) { continue }
        if (Test-ReparsePoint $current) { throw "Codex and Antigravity target '$current' is a link or reparse point, so nothing was written." }
        if (-not (Test-Path -LiteralPath $current -PathType Container)) { throw "Codex and Antigravity target '$current' exists and is not a directory, so nothing was written." }
    }
}

function Assert-CodexDestinationWithinWorkspace {
    param([string] $Path)

    $workspace = [IO.Path]::TrimEndingDirectorySeparator([IO.Path]::GetFullPath($Workspace))
    $target = [IO.Path]::GetFullPath($Path)
    $prefix = $workspace + [IO.Path]::DirectorySeparatorChar
    $comparison = if ($IsWindows) { [StringComparison]::OrdinalIgnoreCase } else { [StringComparison]::Ordinal }
    if (-not $target.StartsWith($prefix, $comparison)) { throw "Agent skill target '$target' resolves outside the workspace, so nothing was written." }
    $current = $workspace
    $relative = [IO.Path]::GetRelativePath($workspace, $target)
    foreach ($segment in $relative.Split([IO.Path]::DirectorySeparatorChar, [StringSplitOptions]::RemoveEmptyEntries)) {
        $current = Join-Path $current $segment
        if ((Test-Path -LiteralPath $current) -and (Test-ReparsePoint $current)) { throw "Agent skill target '$current' is a link or reparse point, so nothing was written." }
    }
}

function Assert-CodexSkillName {
    param([string] $Name)

    if ($Name -match '^(?i:con|prn|aux|nul|com[1-9¹²³]|lpt[1-9¹²³])(?:\..*)?$') { throw "Agent skill folder '$Name' is a reserved Windows device name." }
}

# Before any write: a skill folder that exists must be one the lock records as codex's and still holds the recorded tree.
# Anything else is a folder maxstack did not write, or one a person changed, and the apply stops with nothing written.
function Assert-CodexSkillTargets {
    param([object[]] $Skills, [object[]] $Owned, [switch] $PreserveModified)

    Assert-CodexSkillsPath
    foreach ($skill in $Skills) {
        Assert-CodexSkillName $skill.name
        $relative = "$script:CodexSkillFolder/$($skill.name)"
        $full = Join-MaxstackPath $Workspace (ConvertTo-MaxstackPath $relative)
        Assert-CodexDestinationWithinWorkspace $full
        $parent = Split-Path -Parent $full
        $same = @()
        if (Test-Path -LiteralPath $parent -PathType Container) { $same = @(Get-ChildItem -LiteralPath $parent -Force | Where-Object { Test-OrdinalEqualIgnoreCase $_.Name $skill.name }) }
        if ($same.Count -gt 1) { throw "$relative collides with multiple skill folders by case, so nothing was written." }
        if ($same.Count -eq 1 -and -not (Test-OrdinalEqual $same[0].Name $skill.name)) { throw "$relative collides with skill folder '$($same[0].Name)' by case, so nothing was written." }
        if (-not (Test-Path -LiteralPath $full)) { continue }
        $record = Get-CodexRecord -Owned $Owned -Relative $relative
        if ($null -eq $record) {
            throw "$relative already exists and maxstack did not write it, so nothing was written. Move it aside, then rerun -Apply."
        }
        if ((Test-ReparsePoint $full)) { throw "$relative is a link or reparse point, so nothing was written." }
        if (-not (Test-OrdinalEqual (Get-TreeSha256 $full) $record.sha256)) {
            if (-not $PreserveModified -and $null -eq $record.PSObject.Properties['runtimes']) {
                throw "$relative changed since the last apply, so nothing was written. Move its changes aside, or delete it, then rerun -Apply."
            }
            Write-Host "Kept $relative`: it changed since the last apply."
            $skill | Add-Member -NotePropertyName preserve -NotePropertyValue $true -Force
            $skill | Add-Member -NotePropertyName prior -NotePropertyValue $record -Force
        }
    }
}

# Writes the codex skills, after the checks above. With -RemoveStale, a recorded skill that no layer ships now is removed when
# it still holds its recorded tree, and a changed one is kept and named. A removal passes no -RemoveStale: the folders of the
# layers it removes are deleted by its own plan, which keeps any record it cannot delete.
function Write-CodexSkills {
    param([object[]] $Skills, [object[]] $Owned, [bool] $RemoveStale = $true)

    $wanted = @($Skills | ForEach-Object { "$script:CodexSkillFolder/$($_.name)" })
    $stale = @()
    if ($RemoveStale) { $stale = @($Owned | Where-Object { $null -ne $_ -and @(Get-OwnedRuntimeClaims $_ | Where-Object { Test-OrdinalIn $_ @('codex', 'antigravity') }).Count -gt 0 -and (Test-OrdinalEqual $_.kind 'dir') -and -not (Test-OrdinalIn $_.path $wanted) }) }
    foreach ($record in $stale) {
        $full = Join-MaxstackPath $Workspace (ConvertTo-MaxstackPath $record.path)
        if (-not (Test-Path -LiteralPath $full -PathType Container)) { continue }
        if ((Test-ReparsePoint $full) -or -not (Test-OrdinalEqual (Get-TreeSha256 $full) $record.sha256)) {
            Write-Host "Kept $($record.path): it changed since the last apply, and no layer ships it now"
            continue
        }
        Remove-OwnedTree $full
        Write-Host "Removed the codex skill $($record.path): no layer ships it now"
    }
    $root = Join-MaxstackPath $Workspace (ConvertTo-MaxstackPath $script:CodexSkillFolder)
    foreach ($skill in $Skills) {
        $full = Join-MaxstackPath $root $skill.name
        if (Test-IsTrue (Get-Field $skill 'preserve')) { continue }
        Assert-CodexDestinationWithinWorkspace $full
        Remove-OwnedTree $full
        Copy-SkillTree -Source $skill.source -Destination $full
        Write-Host "Copied codex skill '$($skill.name)' from layer '$($skill.layer)' into $full"
    }
}

# The installed copy of a selected layer.
function Get-CodexGateFolder {
    param([object] $Layer)

    return (Join-MaxstackPath $Workspace ($script:CodexGateFolder + '/' + $Layer.name))
}

# The folder a gate definition is read from: the layer root when it is known, then the installed OpenCode copy, then
# the Claude plugin folder. A definition that none of them holds is not installed.
function Get-GateSourceFolder {
    param([object] $Layer, [string] $Definition)

    $folders = [System.Collections.Generic.List[string]]::new()
    if ($null -ne $Layer.root) { $folders.Add($Layer.root) }
    $folders.Add((Join-MaxstackPath $Workspace ($script:CodexGateFolder + '/' + $Layer.name)))
    $folders.Add((Join-MaxstackPath $Workspace ('.claude/plugins/' + $Layer.name)))
    foreach ($folder in $folders) {
        if (Test-Path -LiteralPath (Join-MaxstackPath $folder $Definition) -PathType Leaf) { return $folder }
    }
    return $null
}

# The folder a gate hook's command runs the adapter from: the installed OpenCode copy when OpenCode is selected, the
# Claude plugin folder when only Claude is, and the layer root when neither runtime writes an installed copy.
function Get-GatePluginFolder {
    param([object] $Layer)

    if ($openCodeSelected -and $Layer.runtimes.ContainsKey('opencode')) { return (Join-MaxstackPath $Workspace ($script:CodexGateFolder + '/' + $Layer.name)) }
    if ($claudeSelected -and $Layer.runtimes.ContainsKey('claude')) { return (Join-MaxstackPath $Workspace ('.claude/plugins/' + $Layer.name)) }
    return $Layer.root
}

# The selected layers whose copy carries a gate definition, in layer order, for the runtimes that take part.
function Get-GateHookLayers {
    param([object[]] $Layers, [string] $Runtime, [string] $Definition)

    $found = [System.Collections.Generic.List[object]]::new()
    foreach ($layer in @($Layers | Where-Object { $_.runtimes.ContainsKey($Runtime) })) {
        if ($null -eq (Get-GateSourceFolder -Layer $layer -Definition $Definition)) { continue }
        $found.Add($layer)
    }
    return $found.ToArray()
}

# The selected layers whose installed copy carries a Codex gate hook: the hook script and the codex runtime library.
# A layer is checked in layer order, and only the layers that selected codex take part.
function Get-CodexGateLayers {
    param([object[]] $Layers)

    $found = [System.Collections.Generic.List[object]]::new()
    if (-not $openCodeSelected) { return @() }
    foreach ($layer in @($Layers | Where-Object { $_.runtimes.ContainsKey('codex') })) {
        $folder = if ($null -ne $layer.root) { $layer.root } else { Get-CodexGateFolder -Layer $layer }
        $hook = Join-Path $folder ($script:CodexGateHookRelative -replace '/', '\')
        $lib = Join-Path $folder ($script:CodexGateLibRelative -replace '/', '\')
        if ((Test-Path -LiteralPath $hook -PathType Leaf) -and (Test-Path -LiteralPath $lib -PathType Leaf)) { $found.Add($layer) }
    }
    return $found.ToArray()
}

# Rewrites each command in a gate definition to run the adapter by absolute path. A definition writes its command as
# `node <adapter relative to the plugin folder>`, and any arguments after the adapter are kept. The adapter is checked
# in the source folder, because the installed copy is written later in the run and does not exist yet on a first apply.
function Set-GateHookCommand {
    param($Value, [string] $Folder, [string] $Source)

    if ($null -eq $Value) { return }
    if ($Value -is [System.Collections.IList]) {
        foreach ($item in $Value) { Set-GateHookCommand -Value $item -Folder $Folder -Source $Source }
        return
    }
    if ($Value -isnot [System.Management.Automation.PSCustomObject]) { return }
    foreach ($property in @($Value.PSObject.Properties)) {
        if ((Test-OrdinalEqual $property.Name 'command') -and ($property.Value -is [string])) {
            $match = [regex]::Match($property.Value, '^node\s+(?<script>\S+)(?<rest>.*)$')
            if (-not $match.Success) { continue }
            $script = $match.Groups['script'].Value.Trim('"', "'")
            if (-not (Test-Path -LiteralPath (Join-MaxstackPath $Source $script) -PathType Leaf)) {
                throw "A gate definition names '$script', which is not in '$Source', so nothing was written."
            }
            $adapter = Join-MaxstackPath $Folder $script
            $property.Value = 'node "' + $adapter.Replace('\', '/') + '"' + $match.Groups['rest'].Value
            continue
        }
        Set-GateHookCommand -Value $property.Value -Folder $Folder -Source $Source
    }
}

# The plan for a gate hook file. It follows the Codex config plan: an unchanged owned file is rewritten, a changed one
# or one maxstack did not write is kept, and a definition that no layer ships now removes an unchanged owned file.
function Get-GateHookConfigPlan {
    param(
        [object[]] $Layers,
        [string] $Runtime,
        [string] $Relative,
        [string] $Definition,
        [string] $Label
    )

    $full = Join-Path $Workspace ($Relative -replace '/', '\')
    $prior = Get-PriorOwnedFileRecord $Relative
    $gateLayers = @(Get-GateHookLayers -Layers $Layers -Runtime $Runtime -Definition $Definition)
    if ($gateLayers.Count -eq 0) {
        if ($null -eq $prior) { return $null }
        if ((Test-Path -LiteralPath $full) -and ((Test-ReparsePoint $full) -or (-not (Test-Path -LiteralPath $full -PathType Leaf)) -or (-not (Test-OrdinalEqual (Get-FileHash -LiteralPath $full -Algorithm SHA256).Hash $prior.sha256)))) {
            Write-Host "Kept ${Relative}: it changed since the last apply, so it was not removed."
            return [pscustomobject]@{ path = $Relative; text = $null; sha256 = $prior.sha256; runtime = $Runtime; layers = @($prior.layers); preserve = $true; label = $Label; remove = $true }
        }
        return [pscustomobject]@{ path = $Relative; text = $null; sha256 = $prior.sha256; runtime = $Runtime; layers = @($prior.layers); label = $Label; remove = $true }
    }
    if ((Test-Path -LiteralPath $full) -and $null -eq $prior) {
        Write-Host "Kept ${Relative}: it exists and was not written by maxstack; add the $Label gate hook by hand."
        return $null
    }
    $preserve = $false
    if ((Test-Path -LiteralPath $full) -and $null -ne $prior) {
        $preserve = (Test-ReparsePoint $full) -or (-not (Test-Path -LiteralPath $full -PathType Leaf))
        if (-not $preserve) { $preserve = -not (Test-OrdinalEqual (Get-FileHash -LiteralPath $full -Algorithm SHA256).Hash $prior.sha256) }
    }
    if ($preserve) {
        Write-Host "Kept ${Relative}: it changed since the last apply, so it was not overwritten."
        return [pscustomobject]@{ path = $Relative; text = $null; sha256 = $prior.sha256; runtime = $Runtime; layers = @($prior.layers); preserve = $true; label = $Label }
    }
    $layer = $gateLayers[0]
    $source = Get-GateSourceFolder -Layer $layer -Definition $Definition
    $folder = Get-GatePluginFolder -Layer $layer
    $definitionJson = Get-Content -LiteralPath (Join-MaxstackPath $source $Definition) -Raw | ConvertFrom-Json
    Set-GateHookCommand -Value $definitionJson -Folder $folder -Source $source
    $text = (ConvertTo-Json -InputObject $definitionJson -Depth 20).Replace("`r`n", "`n").Replace("`r", "`n") + "`n"
    return [pscustomobject]@{ path = $Relative; text = $text; sha256 = Get-TextSha256 $text; runtime = $Runtime; layers = @($layer.name); preserve = $false; label = $Label }
}

function Get-CodexHookConfigPlan {
    param([object[]] $Layers)

    $relative = $script:CodexConfigPath
    $full = Join-Path $Workspace ($relative -replace '/', '\')
    $prior = Get-PriorOwnedFileRecord $relative
    $gateLayers = @(Get-CodexGateLayers -Layers $Layers)
    if ($gateLayers.Count -eq 0) {
        if ($null -eq $prior) { return $null }
        if ((Test-Path -LiteralPath $full) -and ((Test-ReparsePoint $full) -or (-not (Test-Path -LiteralPath $full -PathType Leaf)) -or (-not (Test-OrdinalEqual (Get-FileHash -LiteralPath $full -Algorithm SHA256).Hash $prior.sha256)))) {
            Write-Host 'Kept .codex/config.toml: it changed since the last apply, so it was not removed.'
            return [pscustomobject]@{ path = $relative; text = $null; sha256 = $prior.sha256; runtime = 'codex'; layers = @($prior.layers); preserve = $true; label = 'Codex'; hookHash = (Get-Field $prior 'hookHash'); remove = $true }
        }
        return [pscustomobject]@{ path = $relative; text = $null; sha256 = $prior.sha256; runtime = 'codex'; layers = @($prior.layers); label = 'Codex'; remove = $true }
    }
    if ((Test-Path -LiteralPath $full) -and $null -eq $prior) {
        Write-Host 'Kept .codex/config.toml: it exists and was not written by maxstack; add the Codex gate hook by hand.'
        return $null
    }
    $preserve = $false
    if ((Test-Path -LiteralPath $full) -and $null -ne $prior) {
        $preserve = (Test-ReparsePoint $full) -or (-not (Test-Path -LiteralPath $full -PathType Leaf))
        if (-not $preserve) { $preserve = -not (Test-OrdinalEqual (Get-FileHash -LiteralPath $full -Algorithm SHA256).Hash $prior.sha256) }
    }
    if ($preserve) {
        Write-Host 'Kept .codex/config.toml: it changed since the last apply, so it was not overwritten.'
        return [pscustomobject]@{ path = $relative; text = $null; sha256 = $prior.sha256; runtime = 'codex'; layers = @($prior.layers); preserve = $true; label = 'Codex'; hookHash = (Get-Field $prior 'hookHash') }
    }
    $layer = $gateLayers[0]
    $hook = Join-Path (Get-CodexGateFolder -Layer $layer) ($script:CodexGateHookRelative -replace '/', '\')
    $command = 'node ' + $hook.Replace('\', '/') + ' codex'
    $escapedCommand = $command.Replace('\', '\\').Replace('"', '\"')
    $text = "$script:CodexHookHeader`n`nhooks.PreToolUse = [{ matcher = ""Bash"", hooks = [{ type = ""command"", command = ""$escapedCommand"", timeout = 30 }] }]`n"
    $hookHash = $null
    if ($Status -or $Apply) {
        $output = @(& node (Join-Path $PSScriptRoot $script:CodexHookStatusScript) --workspace $Workspace --hook-command $command 2>&1 | ForEach-Object { [string] $_ })
        $code = $LASTEXITCODE
        if ($code -eq 0) {
            try { $probe = ($output -join "`n").Trim() | ConvertFrom-Json -ErrorAction Stop; $hookHash = [string] $probe.hash }
            catch { Write-Warning 'Codex could not report the hook hash; the hook file will still be written.' }
        } else { Write-Warning "Codex could not report the hook hash; the hook file will still be written: $(($output -join ' ').Trim())" }
    }
    if ($null -eq $hookHash -and $null -ne $prior) { $hookHash = Get-Field $prior 'hookHash' }
    return [pscustomobject]@{ path = $relative; text = $text; sha256 = Get-TextSha256 $text; runtime = 'codex'; layers = @($layer.name); preserve = $false; label = 'Codex'; hookHash = $hookHash }
}

